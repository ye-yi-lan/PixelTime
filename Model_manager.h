    Model* get_model(Model_type lx,int id){
      switch(lx){
        case Model_type::numbers_s: return &numbers_s[id];break;
        case Model_type::numbers_b: return &numbers_b[id];break;
        case Model_type::numbers_b_thin: return &numbers_b_thin[id];break;
        case Model_type::letters: return &letters[id];break;
        case Model_type::others: return &others[id];break;
        case Model_type::icons: return &icons[id];break;
      }
    }
    Model* get_model(Model_type lx,Scene_type id){
      return get_model(lx,static_cast<int>(id));
    }
    Model* get_letter(char l){
      int id=l-65;
      return get_model(Model_type::letters,id);
    }
    Model* get_number(int n,bool small=1,bool thin=0){
      if(small){
        return get_model(Model_type::numbers_s,n);
      }
      else{
        if((!thin)||n>5){
          return get_model(Model_type::numbers_b,n);
        }else{
          return get_model(Model_type::numbers_b_thin,n);
        }
      }
    }
